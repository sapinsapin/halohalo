"""
Which languages and voices this server knows, from assets.json (a copy of
dashboard/assets.json, generated by prepare_space_assets.py at the repo root;
regenerate there and copy rather than editing here).

A voice is a PLD speaker id. Orpheus adapters were trained with the speaker
id as the voice name in the prompt ("CEB_0200: ..."), so any speaker of that
language's training set is a voice; the ones listed are the two per language
the dashboard demos. SpeechT5 needs the matching x-vector file, so for it the
list is exhaustive.
"""

import json
from pathlib import Path

ROOT = Path(__file__).parent
ASSETS = json.loads((ROOT / "assets.json").read_text(encoding="utf-8"))
LANGS: dict = ASSETS["languages"]

# Language as a code ("fil") or display name ("Filipino"), case-insensitive.
LANG_ALIASES: dict[str, str] = {}
for _code, _meta in LANGS.items():
    LANG_ALIASES[_code.lower()] = _code
    LANG_ALIASES[_meta["name"].lower()] = _code
# ISO 639-1 / common spellings callers reasonably try.
LANG_ALIASES.update({"tl": "fil", "tgl": "fil", "tagalog": "fil", "filipino": "fil",
                     "en": "eng", "english": "eng", "ceb": "ceb", "cebuano": "ceb",
                     "bisaya": "ceb", "bik": "bcl", "bikol": "bcl", "ilokano": "ilo",
                     "ilocano": "ilo", "pampangan": "pam", "kapampangan": "pam",
                     "waray-waray": "war"})

# Where every language trains under Whisper's <|tl|> token except English.
WHISPER_LANGUAGE = {code: "tagalog" for code in LANGS}
WHISPER_LANGUAGE["eng"] = "english"


def resolve_lang(value, served: tuple[str, ...], default: str) -> str | None:
    """A served language code, the default for an empty value, None if unknown."""
    if value is None or str(value).strip() == "":
        return default if default in served else (served[0] if served else None)
    code = LANG_ALIASES.get(str(value).strip().lower())
    return code if code in served else None


def resolve_voice(lang: str, value) -> dict:
    """Pick a voice for a language. Unknown values fall back silently to the
    first voice, as the TTS contract promises; a speaker id in the right
    format but not on the list is passed through for Orpheus (it may well be
    a training speaker) with no x-vector file."""
    voices = LANGS[lang]["voices"]
    if not voices:
        raise RuntimeError(f"no voice preset for {lang}")
    if value:
        want = str(value).strip()
        low = want.lower()
        for v in voices:
            if low in (v["id"].lower(), v["gender"].lower()):
                return v
        if want.isdigit() and int(want) < len(voices):
            return voices[int(want)]
        prefix = voices[0]["id"].split("_")[0]
        if want.upper().startswith(prefix + "_") and want[len(prefix) + 1:].isdigit():
            return {"id": want.upper(), "gender": "unknown", "file": None}
    return voices[0]


def catalog(served: tuple[str, ...]) -> dict:
    return {c: {"name": LANGS[c]["name"],
                "voices": [{"id": v["id"], "gender": v["gender"]}
                           for v in LANGS[c]["voices"]]}
            for c in served if c in LANGS}
